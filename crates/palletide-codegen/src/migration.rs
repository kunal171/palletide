//! Conservative schema evolution. Applied migrations are immutable; unsafe data
//! transformations require an explicit hand-written migration and baseline.
use crate::model::{Field, Schema};

fn quote(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}
fn definition(field: &Field) -> String {
    format!(
        "{} {}{}",
        quote(&field.column),
        field.pg_type(),
        if field.nullable { "" } else { " NOT NULL" }
    )
}

/// Plan additive SQL; reject changes requiring a data migration or destructive DDL.
/// The checkpoint prevents historical undo rows from being interpreted using a
/// different table layout. It commits atomically with the handler migration.
pub fn plan(previous: &Schema, next: &Schema) -> Result<Option<String>, String> {
    if previous == next {
        return Ok(None);
    }
    let mut sql = String::new();
    for old in &previous.entities {
        let entity = next
            .entity(&old.name)
            .ok_or_else(|| format!("removing entity {} requires a manual migration", old.name))?;
        for before in &old.fields {
            let after = entity
                .fields
                .iter()
                .find(|f| f.name == before.name)
                .ok_or_else(|| {
                    format!(
                        "removing {}.{} requires a manual migration",
                        old.name, before.name
                    )
                })?;
            if before.ty != after.ty
                || before.is_id != after.is_id
                || (before.nullable && !after.nullable)
                || before.unique != after.unique
            {
                return Err(format!(
                    "changing {}.{} requires a manual data migration",
                    old.name, before.name
                ));
            }
            if !before.nullable && after.nullable {
                sql.push_str(&format!(
                    "ALTER TABLE {} ALTER COLUMN {} DROP NOT NULL;\n",
                    quote(&old.table),
                    quote(&before.column)
                ));
            }
            if before.indexed != after.indexed && !after.is_id && !after.unique {
                let index = quote(&format!("{}_{}_idx", old.table, after.column));
                if after.indexed {
                    sql.push_str(&format!(
                        "CREATE INDEX {index} ON {} ({});\n",
                        quote(&old.table),
                        quote(&after.column)
                    ));
                } else {
                    sql.push_str(&format!("DROP INDEX IF EXISTS {index};\n"));
                }
            }
        }
        for field in &entity.fields {
            if old.fields.iter().any(|f| f.name == field.name) {
                continue;
            }
            if !field.nullable || field.is_id || field.unique {
                return Err(format!(
                    "new field {}.{} must be nullable; backfill before adding constraints",
                    entity.name, field.name
                ));
            }
            sql.push_str(&format!(
                "ALTER TABLE {} ADD COLUMN {};\n",
                quote(&entity.table),
                definition(field)
            ));
            if field.indexed {
                sql.push_str(&format!(
                    "CREATE INDEX {} ON {} ({});\n",
                    quote(&format!("{}_{}_idx", entity.table, field.column)),
                    quote(&entity.table),
                    quote(&field.column)
                ));
            }
        }
    }
    for enumeration in &previous.enums {
        if let Some(next) = next.enums.iter().find(|e| e.name == enumeration.name) {
            if enumeration.values.iter().any(|v| !next.values.contains(v)) {
                return Err(format!(
                    "removing enum values from {} requires a data migration",
                    enumeration.name
                ));
            }
        } else {
            return Err(format!(
                "removing enum {} requires a manual migration",
                enumeration.name
            ));
        }
    }
    let new_entities = next
        .entities
        .iter()
        .filter(|e| previous.entity(&e.name).is_none())
        .cloned()
        .collect();
    let new_schema = Schema {
        entities: new_entities,
        enums: next.enums.clone(),
    };
    if !new_schema.entities.is_empty() {
        sql.push_str(&crate::gen_sql::render(&new_schema));
    }
    if sql.is_empty() {
        return Ok(None);
    }
    Ok(Some(format!("-- @generated by palletide-codegen; review before applying.\n-- Earlier entity undo history cannot cross a schema change.\nSELECT palletide_checkpoint_entities();\n\n{sql}")))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse_schema;
    #[test]
    fn additive_plan_preserves_old_columns_and_rejects_data_loss() {
        let before = parse_schema("type Account @entity { id: ID! balance: BigInt! }").unwrap();
        let after =
            parse_schema("type Account @entity { id: ID! balance: BigInt! name: String @index }")
                .unwrap();
        let sql = plan(&before, &after).unwrap().unwrap();
        assert!(sql.contains("ADD COLUMN \"name\" TEXT"));
        assert!(sql.contains("checkpoint_entities"));
        assert!(!sql.contains("DROP TABLE"));
        assert!(plan(&after, &before).is_err());
        assert!(plan(&before, &before).unwrap().is_none());
        let required =
            parse_schema("type Account @entity { id: ID! balance: BigInt! name: String! }")
                .unwrap();
        assert!(plan(&before, &required).is_err());
    }
}
